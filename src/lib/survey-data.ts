export function interpretMean(mean: number): { label: string; tone: string } {
  if (mean >= 2.34) return { label: "اتجاه مرتفع", tone: "text-emerald-600" };
  if (mean >= 1.67) return { label: "اتجاه متوسط", tone: "text-amber-600" };
  return { label: "اتجاه منخفض", tone: "text-red-600" };
}
