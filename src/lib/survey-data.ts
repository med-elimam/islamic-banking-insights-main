export function interpretMean(mean: number): { label: string; tone: string } {
  if (mean >= 4.21) return { label: "اتجاه مرتفع جداً", tone: "text-emerald-700" };
  if (mean >= 3.41) return { label: "اتجاه مرتفع", tone: "text-emerald-600" };
  if (mean >= 2.61) return { label: "اتجاه متوسط", tone: "text-amber-600" };
  if (mean >= 1.81) return { label: "اتجاه منخفض", tone: "text-orange-600" };
  return { label: "اتجاه منخفض جداً", tone: "text-red-600" };
}
